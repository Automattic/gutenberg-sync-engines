/**
 * Twin of `wp_de_rtc_create_automerge_update_for_content_change`: builds
 * the block-native client-update descriptor for a (base, proposed) pair.
 *
 * @param base  Base post content (the canonical content of the
 *              proposal's declared base version, as the server sent it).
 * @param next  Proposed post content.
 * @param actor Actor label for operation ids (not fingerprinted).
 * @return The client update descriptor.
 */
export function buildDeRtcClientUpdate(
	base: string,
	next: string,
	actor: string
): DeRtcClientUpdate {
	base = canonicalizeCoreBlockNames( base );
	next = canonicalizeCoreBlockNames( next );
	const baseRecords = getTopLevelBlockRecords( base );
	const nextRecords = getTopLevelBlockRecords( next );

	if ( null === baseRecords || null === nextRecords ) {
		const changeRange = getContentChangeRange( base, next );
		return {
			format: 'native-automerge-blocks-v1',
			schema: 'de-rtc-automerge-v1',
			operations: [
				{
					type: 'document.replace_unsupported',
					automergePrimitive: 'Automerge.Map.set',
					actor,
					sequence: 0,
					id: `${ actor }:0`,
					baseContentHash: hashDeRtcContent( base ),
					proposedContentHash: hashDeRtcContent( next ),
					changeRange,
				},
			],
			stateVector: { [ actor ]: 1 },
			baseContentHash: hashDeRtcContent( base ),
			proposedContentHash: hashDeRtcContent( next ),
			baseBlockCount: null,
			proposedBlockCount: null,
		};
	}

	const operations = getBlockNativeOperations(
		baseRecords,
		nextRecords,
		actor
	);

	return {
		format: 'native-automerge-blocks-v1',
		schema: 'de-rtc-automerge-v1',
		operations,
		stateVector:
			operations.length > 0 ? { [ actor ]: operations.length } : {},
		baseContentHash: hashDeRtcContent( base ),
		proposedContentHash: hashDeRtcContent( next ),
		baseBlockCount: baseRecords.length,
		proposedBlockCount: nextRecords.length,
	};
}

/**
 * Twin of `wp_de_rtc_get_automerge_block_native_operation_fingerprints`
 * (+ the text-splice fingerprint helper). Exposed for the cross-language
 * vector suite and client-side self-checks; the authoritative comparison
 * happens server-side in PHP.
 *
 * @param operations Block-native operations.
 * @return Comparable fingerprints.
 */
export function fingerprintDeRtcOperations(
	operations: Array< Record< string, unknown > >
): Array< Record< string, unknown > > {
	const toIntArray = ( value: unknown ): number[] | null =>
		Array.isArray( value )
			? value.map( ( entry ) => Math.trunc( Number( entry ) || 0 ) )
			: null;

	return operations.map( ( operation ) => {
		const splice = operation.textSplice as
			| Record< string, unknown >
			| undefined;
		const insertText =
			'string' === typeof splice?.insertText
				? ( splice.insertText as string )
				: '';
		return {
			type: 'string' === typeof operation.type ? operation.type : '',
			path: toIntArray( operation.path ),
			fromPath: toIntArray( operation.fromPath ),
			toPath: toIntArray( operation.toPath ),
			index:
				undefined !== operation.index && null !== operation.index
					? Math.trunc( Number( operation.index ) || 0 )
					: null,
			blockHash:
				'string' === typeof operation.blockHash
					? operation.blockHash
					: null,
			baseBlockHash:
				'string' === typeof operation.baseBlockHash
					? operation.baseBlockHash
					: null,
			proposedBlockHash:
				'string' === typeof operation.proposedBlockHash
					? operation.proposedBlockHash
					: null,
			blockName:
				'string' === typeof operation.blockName
					? operation.blockName
					: null,
			baseBlockName:
				'string' === typeof operation.baseBlockName
					? operation.baseBlockName
					: null,
			proposedBlockName:
				'string' === typeof operation.proposedBlockName
					? operation.proposedBlockName
					: null,
			serializedBlockHash:
				'string' === typeof operation.serializedBlock
					? hashDeRtcContent( operation.serializedBlock )
					: null,
			changedTextIndexes: toIntArray( operation.changedTextIndexes ),
			textSplice: splice
				? {
						changed: Boolean( splice.changed ),
						start: Math.trunc( Number( splice.start ) || 0 ),
						deleteCount: Math.trunc(
							Number( splice.deleteCount ) || 0
						),
						insertTextHash: sha256Hex( insertText ),
						insertCount: Math.trunc(
							Number( splice.insertCount ) || 0
						),
						end: Math.trunc( Number( splice.end ) || 0 ),
						delta: Math.trunc( Number( splice.delta ) || 0 ),
				  }
				: null,
		};
	} );
}
