/**
 * Twin of core PHP `serialize_block_attributes()` — identical to
 * `@wordpress/blocks`' serializeAttributes (the two are the established
 * cross-language save-format contract).
 *
 * @param attrs Block attributes.
 * @return Serialized attribute JSON.
 */
function serializeBlockAttributes( attrs: Record< string, unknown > ): string {
	return JSON.stringify( attrs )
		.replace( /--/g, '\\u002d\\u002d' )
		.replace( /</g, '\\u003c' )
		.replace( />/g, '\\u003e' )
		.replace( /&/g, '\\u0026' )
		.replace( /\\"/g, '\\u0022' );
}

/**
 * Twin of core PHP `serialize_block()` over the grammar parser's output.
 *
 * @param block Parsed grammar block.
 * @return Serialized block.
 */
function serializeGrammarBlock( block: ParsedGrammarBlock ): string {
	let content = '';
	let innerIndex = 0;
	for ( const chunk of block.innerContent ) {
		content +=
			'string' === typeof chunk
				? chunk
				: serializeGrammarBlock( block.innerBlocks[ innerIndex++ ] );
	}

	if ( null === block.blockName ) {
		return content;
	}

	const name = block.blockName.startsWith( 'core/' )
		? block.blockName.slice( 5 )
		: block.blockName;
	const attrs = block.attrs ?? {};
	const serializedAttrs =
		0 === Object.keys( attrs ).length
			? ''
			: serializeBlockAttributes( attrs ) + ' ';

	if ( '' === content ) {
		return `<!-- wp:${ name } ${ serializedAttrs }/-->`;
	}

	return `<!-- wp:${ name } ${ serializedAttrs }-->${ content }<!-- /wp:${ name } -->`;
}

/**
 * Twin of PHP `parse_blocks()` + serialize round trip.
 *
 * @param content Serialized content.
 * @return Parsed blocks and their re-serialization.
 */
function parseAndReserialize( content: string ): {
	blocks: ParsedGrammarBlock[];
	roundtrip: string;
} {
	const blocks = parseBlockGrammar( content ) as ParsedGrammarBlock[];
	let roundtrip = '';
	for ( const block of blocks ) {
		roundtrip += serializeGrammarBlock( block );
	}
	return { blocks, roundtrip };
}

