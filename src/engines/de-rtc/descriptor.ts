interface RichTextModel {
	text: string;
	marks: Array< { type: string; start: number; end: number } >;
}

/**
 * Twin of `wp_de_rtc_get_paragraph_rich_text_block_parts`.
 *
 * @param block Serialized block record.
 * @return Open/html/close parts or null.
 */
function getParagraphParts(
	block: string
): { open: string; html: string; close: string } | null {
	const match =
		/^(<!--\s+wp:paragraph\b[\s\S]*?-->\s*<p\b[^>]*>)([\s\S]*?)(<\/p>\s*<!--\s+\/wp:paragraph\s+-->)$/i.exec(
			block
		);
	if ( ! match ) {
		return null;
	}
	return { open: match[ 1 ], html: match[ 2 ], close: match[ 3 ] };
}

/**
 * Twin of PHP `html_entity_decode( $t, ENT_QUOTES | ENT_HTML5, 'UTF-8' )`.
 *
 * PHP decodes ONLY semicolon-terminated references from the HTML5 table
 * (verified by vector `entity-no-semicolon`: a bare `&amp` stays
 * literal), while raw browser text parsing also legacy-decodes bare
 * named forms. So: extract each well-formed `&...;` candidate and decode
 * it in isolation via textarea RCDATA (the browser's HTML5 named table =
 * PHP's ENT_HTML5 table); a candidate the browser only PARTIALLY decodes
 * (e.g. `&ampx;` → `&x;`, still ending in `;`) is not a table entry and
 * stays literal, matching PHP.
 *
 * @param text Text token (no complete tags).
 * @return Decoded text.
 */
function decodeHtmlEntities( text: string ): string {
	if ( -1 === text.indexOf( '&' ) ) {
		return text;
	}
	return text.replace(
		/&(?:[a-zA-Z][a-zA-Z0-9]*|#[0-9]+|#[xX][0-9a-fA-F]+);/g,
		( candidate ) => {
			const textarea = document.createElement( 'textarea' );
			textarea.innerHTML = candidate;
			const decoded = textarea.value;
			if ( decoded === candidate ) {
				return candidate; // Unknown reference.
			}
			// A NAMED candidate whose decode still ends in ';' was only
			// partially matched (a numeric one always decodes whole —
			// `&#59;` legitimately IS ';').
			if ( '#' !== candidate[ 1 ] && decoded.endsWith( ';' ) ) {
				return candidate;
			}
			return decoded;
		}
	);
}

/**
 * Twin of `wp_de_rtc_pop_rich_text_active_mark`.
 *
 * @param activeMarks Active mark stack (mutated).
 * @param mark        Mark to pop.
 * @return Whether the mark was popped.
 */
function popActiveMark( activeMarks: string[], mark: string ): boolean {
	for ( let index = activeMarks.length - 1; index >= 0; index-- ) {
		if ( activeMarks[ index ] === mark ) {
			activeMarks.splice( index, 1 );
			return true;
		}
	}
	return false;
}

/**
 * Twin of `wp_de_rtc_coalesce_rich_text_marks`.
 *
 * @param marks Mark ranges.
 * @return Coalesced mark ranges.
 */
function coalesceMarks(
	marks: RichTextModel[ 'marks' ]
): RichTextModel[ 'marks' ] {
	const sorted = [ ...marks ].sort( ( a, b ) => {
		if ( a.type === b.type ) {
			if ( a.start === b.start ) {
				return a.end - b.end;
			}
			return a.start - b.start;
		}
		return a.type < b.type ? -1 : 1;
	} );

	const coalesced: RichTextModel[ 'marks' ] = [];
	for ( const mark of sorted ) {
		const last = coalesced[ coalesced.length - 1 ];
		if ( last && last.type === mark.type && last.end === mark.start ) {
			last.end = mark.end;
		} else {
			coalesced.push( { ...mark } );
		}
	}
	return coalesced;
}

/**
 * Twin of `wp_de_rtc_get_rich_text_format_model`.
 *
 * @param html Paragraph inner HTML.
 * @return Rich-text model or null for unsupported HTML.
 */
function getRichTextFormatModel( html: string ): RichTextModel | null {
	// preg_split with DELIM_CAPTURE | NO_EMPTY.
	const tokens = html.split( /(<[^>]+>)/ ).filter( ( t ) => '' !== t );

	let text = '';
	const marks: RichTextModel[ 'marks' ] = [];
	const activeMarks: string[] = [];
	let offset = 0;

	for ( const token of tokens ) {
		// PHP classifies on the first character alone: a stray unpaired
		// '<' makes the token a (never-matching) tag and the model null.
		if ( '<' === token[ 0 ] ) {
			const normalized = token.replace( /\s+/g, '' ).toLowerCase();

			if ( '<strong>' === normalized || '<b>' === normalized ) {
				activeMarks.push( 'strong' );
				continue;
			}
			if ( '</strong>' === normalized || '</b>' === normalized ) {
				if ( ! popActiveMark( activeMarks, 'strong' ) ) {
					return null;
				}
				continue;
			}
			if ( '<em>' === normalized || '<i>' === normalized ) {
				activeMarks.push( 'em' );
				continue;
			}
			if ( '</em>' === normalized || '</i>' === normalized ) {
				if ( ! popActiveMark( activeMarks, 'em' ) ) {
					return null;
				}
				continue;
			}
			return null;
		}

		const decoded = decodeHtmlEntities( token );
		for ( const char of splitCodePoints( decoded ) ) {
			text += char;
			for ( const mark of activeMarks ) {
				marks.push( { type: mark, start: offset, end: offset + 1 } );
			}
			offset++;
		}
	}

	if ( activeMarks.length > 0 ) {
		return null;
	}
	return { text, marks: coalesceMarks( marks ) };
}

/**
 * Twin of `wp_de_rtc_rich_text_has_mark_at`.
 *
 * @param model Rich-text model.
 * @param mark  Mark type.
 * @param index Character index.
 * @return Whether the mark covers the index.
 */
function hasMarkAt(
	model: RichTextModel,
	mark: string,
	index: number
): boolean {
	return model.marks.some(
		( range ) =>
			range.type === mark && range.start <= index && index < range.end
	);
}

/**
 * Twin of `wp_de_rtc_get_rich_text_changed_indexes`.
 *
 * @param base Base model.
 * @param next Next model.
 * @return Changed character indexes.
 */
function getChangedMarkIndexes(
	base: RichTextModel,
	next: RichTextModel
): number[] {
	const changed: number[] = [];
	const count = splitCodePoints( base.text ).length;

	for ( let index = 0; index < count; index++ ) {
		for ( const mark of [ 'strong', 'em' ] ) {
			if (
				hasMarkAt( base, mark, index ) !==
				hasMarkAt( next, mark, index )
			) {
				changed.push( index );
				break;
			}
		}
	}
	return changed;
}

/**
 * Twin of `wp_de_rtc_get_rich_text_text_splice` +
 * `wp_de_rtc_format_rich_text_text_splice_for_client` (client shape,
 * code-point units).
 *
 * @param baseText Base visible text.
 * @param nextText Next visible text.
 * @return Client-shaped text-splice evidence.
 */
function getTextSplice( baseText: string, nextText: string ) {
	if ( baseText === nextText ) {
		return {
			changed: false,
			start: 0,
			deleteCount: 0,
			insertText: '',
			insertCount: 0,
			end: 0,
			delta: 0,
		};
	}

	const baseChars = splitCodePoints( baseText );
	const nextChars = splitCodePoints( nextText );
	let prefix = 0;
	while (
		prefix < baseChars.length &&
		prefix < nextChars.length &&
		baseChars[ prefix ] === nextChars[ prefix ]
	) {
		prefix++;
	}
	let suffix = 0;
	while (
		suffix < baseChars.length - prefix &&
		suffix < nextChars.length - prefix &&
		baseChars[ baseChars.length - 1 - suffix ] ===
			nextChars[ nextChars.length - 1 - suffix ]
	) {
		suffix++;
	}

	const deleteCount = baseChars.length - prefix - suffix;
	const insertChars = nextChars.slice( prefix, nextChars.length - suffix );

	return {
		changed: true,
		start: prefix,
		deleteCount,
		insertText: insertChars.join( '' ),
		insertCount: insertChars.length,
		end: prefix + deleteCount,
		delta: insertChars.length - deleteCount,
	};
}

