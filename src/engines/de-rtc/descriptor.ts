/*
 * The DE-RTC block-native client-update descriptor builder: the
 * client-side twin of the frozen merge core's
 * `wp_de_rtc_create_automerge_update_for_content_change()`.
 *
 * The descriptor is TAMPER EVIDENCE, not merge input: the server derives
 * the exact same update from the (base, proposed) pair and rejects the
 * proposal when the fingerprints disagree (`de_rtc_sync_meta_tampered`).
 * Merge outcomes are identical with or without it. Because a mismatch
 * REJECTS a legitimate save, every function here must byte-match its PHP
 * twin — the contract is enforced by PHP-generated fixture vectors
 * (tests/js/engines/de-rtc/test-vectors/, regenerated by
 * `tests/tools/generate-de-rtc-descriptor-vectors.php`). Do not change
 * behavior here without regenerating and re-running the vectors.
 *
 * Only fingerprinted fields need parity: operation types/paths/ordering,
 * sha256 content hashes, block names, `textSplice` (code-point counts +
 * insert-text hash), and `changedTextIndexes`. (`changeRange` is carried
 * for shape fidelity but is NOT fingerprinted server-side.)
 */

interface ParsedGrammarBlock {
	blockName: string | null;
	attrs: Record< string, unknown > | null;
	innerBlocks: ParsedGrammarBlock[];
	innerHTML: string;
	innerContent: Array< string | null >;
}

export interface DeRtcClientUpdate {
	format: 'native-automerge-blocks-v1';
	schema: 'de-rtc-automerge-v1';
	operations: Array< Record< string, unknown > >;
	stateVector: Record< string, number >;
	baseContentHash: string;
	proposedContentHash: string;
	baseBlockCount: number | null;
	proposedBlockCount: number | null;
}

