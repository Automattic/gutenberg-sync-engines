/**
 * Twin of `wp_de_rtc_get_automerge_block_native_rich_text_operation`.
 *
 * @param baseBlock Base serialized block.
 * @param nextBlock Proposed serialized block.
 * @param baseHash  Base block hash.
 * @param nextHash  Proposed block hash.
 * @param blockName Block name.
 * @param path      Top-level ordinal path.
 * @return Operation body or null.
 */
function getRichTextOperation(
	baseBlock: string,
	nextBlock: string,
	baseHash: string,
	nextHash: string,
	blockName: string,
	path: number[]
): Record< string, unknown > | null {
	const base = getParagraphParts( baseBlock );
	const next = getParagraphParts( nextBlock );
	if (
		! base ||
		! next ||
		base.open !== next.open ||
		base.close !== next.close
	) {
		return null;
	}

	const baseModel = getRichTextFormatModel( base.html );
	const nextModel = getRichTextFormatModel( next.html );
	if ( ! baseModel || ! nextModel ) {
		return null;
	}

	if ( baseModel.text !== nextModel.text ) {
		return {
			type: 'block.rich_text_content',
			automergePrimitive: 'Automerge.Text.splice',
			path,
			blockUid: 'top:' + baseHash,
			blockName,
			field: 'innerHTML',
			baseBlockHash: baseHash,
			proposedBlockHash: nextHash,
			textSplice: getTextSplice( baseModel.text, nextModel.text ),
			serializedBlock: nextBlock,
		};
	}

	return {
		type: 'block.rich_text_format',
		automergePrimitive: 'Automerge.Text.mark',
		path,
		blockUid: 'top:' + baseHash,
		blockName,
		field: 'innerHTML',
		baseBlockHash: baseHash,
		proposedBlockHash: nextHash,
		changedTextIndexes: getChangedMarkIndexes( baseModel, nextModel ),
		serializedBlock: nextBlock,
	};
}

/**
 * Twin of `wp_de_rtc_get_automerge_block_native_update_operation`.
 *
 * @param baseBlock Base serialized block.
 * @param nextBlock Proposed serialized block.
 * @param baseHash  Base block hash.
 * @param nextHash  Proposed block hash.
 * @param path      Top-level ordinal path.
 * @return Operation body.
 */
function getUpdateOperation(
	baseBlock: string,
	nextBlock: string,
	baseHash: string,
	nextHash: string,
	path: number[]
): Record< string, unknown > {
	const baseBlockName = getBlockRecordName( baseBlock );
	const nextBlockName = getBlockRecordName( nextBlock );

	if ( null !== baseBlockName && baseBlockName === nextBlockName ) {
		const richTextOperation = getRichTextOperation(
			baseBlock,
			nextBlock,
			baseHash,
			nextHash,
			baseBlockName,
			path
		);
		if ( null !== richTextOperation ) {
			return richTextOperation;
		}

		return {
			type: 'block.update_serialized',
			automergePrimitive: 'Automerge.Map.set',
			path,
			blockUid: 'top:' + baseHash,
			blockName: baseBlockName,
			baseBlockHash: baseHash,
			proposedBlockHash: nextHash,
			changeRange: getContentChangeRange( baseBlock, nextBlock ),
			serializedBlock: nextBlock,
		};
	}

	return {
		type: 'block.replace',
		automergePrimitive: 'Automerge.Map.set+Automerge.List.insert',
		path,
		blockUid: 'top:' + nextHash,
		baseBlockHash: baseHash,
		proposedBlockHash: nextHash,
		baseBlockName,
		proposedBlockName: nextBlockName,
		serializedBlock: nextBlock,
	};
}

/**
 * Twin of `wp_de_rtc_have_same_serialized_block_multiset`.
 *
 * @param first  First hash list.
 * @param second Second hash list.
 * @return Whether the multisets match.
 */
function sameHashMultiset( first: string[], second: string[] ): boolean {
	if ( first.length !== second.length ) {
		return false;
	}
	const counts = new Map< string, number >();
	for ( const hash of first ) {
		counts.set( hash, ( counts.get( hash ) ?? 0 ) + 1 );
	}
	for ( const hash of second ) {
		const count = counts.get( hash ) ?? 0;
		if ( 0 === count ) {
			return false;
		}
		counts.set( hash, count - 1 );
	}
	return true;
}

/**
 * Twin of `wp_de_rtc_get_automerge_block_native_operations` (+ the
 * append helper's actor/sequence/id stamping).
 *
 * @param baseRecords Base serialized records.
 * @param nextRecords Proposed serialized records.
 * @param actor       Actor label.
 * @return Block-native operations.
 */
function getBlockNativeOperations(
	baseRecords: string[],
	nextRecords: string[],
	actor: string
): Array< Record< string, unknown > > {
	const operations: Array< Record< string, unknown > > = [];
	const append = ( operation: Record< string, unknown > ) => {
		const sequence = operations.length;
		operations.push( {
			actor,
			sequence,
			id: `${ actor }:${ sequence }`,
			...operation,
		} );
	};

	const baseHashes = baseRecords.map( hashDeRtcContent );
	const nextHashes = nextRecords.map( hashDeRtcContent );

	const recordsEqual =
		baseRecords.length === nextRecords.length &&
		baseRecords.every(
			( record, index ) => record === nextRecords[ index ]
		);

	if (
		baseRecords.length === nextRecords.length &&
		! recordsEqual &&
		sameHashMultiset( baseHashes, nextHashes ) &&
		new Set( baseHashes ).size === baseHashes.length
	) {
		nextRecords.forEach( ( nextRecord, index ) => {
			if ( baseRecords[ index ] === nextRecord ) {
				return;
			}
			const fromIndex = baseHashes.indexOf( nextHashes[ index ] );
			if ( -1 !== fromIndex && fromIndex !== index ) {
				append( {
					type: 'block.move',
					automergePrimitive: 'Automerge.List.move',
					fromPath: [ fromIndex ],
					toPath: [ index ],
					blockUid: 'top:' + nextHashes[ index ],
					blockHash: nextHashes[ index ],
				} );
			}
		} );
		return operations;
	}

	if ( baseRecords.length === nextRecords.length ) {
		baseRecords.forEach( ( baseRecord, index ) => {
			if ( baseRecord === nextRecords[ index ] ) {
				return;
			}
			append(
				getUpdateOperation(
					baseRecord,
					nextRecords[ index ],
					baseHashes[ index ],
					nextHashes[ index ],
					[ index ]
				)
			);
		} );
		return operations;
	}

	let prefix = 0;
	while (
		prefix < baseRecords.length &&
		prefix < nextRecords.length &&
		baseRecords[ prefix ] === nextRecords[ prefix ]
	) {
		prefix++;
	}
	let suffix = 0;
	while (
		suffix < baseRecords.length - prefix &&
		suffix < nextRecords.length - prefix &&
		baseRecords[ baseRecords.length - 1 - suffix ] ===
			nextRecords[ nextRecords.length - 1 - suffix ]
	) {
		suffix++;
	}

	for (
		let index = baseRecords.length - suffix - 1;
		index >= prefix;
		index--
	) {
		append( {
			type: 'block.delete',
			automergePrimitive: 'Automerge.List.delete',
			path: [ index ],
			index,
			blockUid: 'top:' + baseHashes[ index ],
			blockHash: baseHashes[ index ],
		} );
	}

	for ( let index = prefix; index < nextRecords.length - suffix; index++ ) {
		append( {
			type: 'block.insert',
			automergePrimitive: 'Automerge.List.insert',
			path: [ index ],
			index,
			blockUid: 'top:' + nextHashes[ index ],
			blockHash: nextHashes[ index ],
			blockName: getBlockRecordName( nextRecords[ index ] ),
			serializedBlock: nextRecords[ index ],
		} );
	}

	return operations;
}

