/**
 * Twin of `wp_de_rtc_split_utf8_string` (Unicode code points).
 * @param text
 */
const splitCodePoints = ( text: string ): string[] => Array.from( text );

/**
 * Twin of `wp_de_rtc_get_automerge_content_change_descriptor`: single
 * change region by code-point prefix/suffix, measured in UTF-16 units.
 *
 * @param base Base text.
 * @param next Next text.
 * @return Change-range descriptor (client key shape).
 */
function getContentChangeRange( base: string, next: string ) {
	const baseChars = splitCodePoints( base );
	const nextChars = splitCodePoints( next );
	let prefix = 0;
	while (
		prefix < baseChars.length &&
		prefix < nextChars.length &&
		baseChars[ prefix ] === nextChars[ prefix ]
	) {
		prefix++;
	}
	let suffix = 0;
	while (
		suffix < baseChars.length - prefix &&
		suffix < nextChars.length - prefix &&
		baseChars[ baseChars.length - 1 - suffix ] ===
			nextChars[ nextChars.length - 1 - suffix ]
	) {
		suffix++;
	}

	const deletedText = baseChars
		.slice( prefix, baseChars.length - suffix )
		.join( '' );
	const insertText = nextChars
		.slice( prefix, nextChars.length - suffix )
		.join( '' );
	// UTF-16 code-unit lengths (JS string length IS the UTF-16 length).
	const index = baseChars.slice( 0, prefix ).join( '' ).length;
	const deleteLength = deletedText.length;
	const insertLength = insertText.length;

	return {
		start: index,
		end: index + deleteLength,
		deleteLength,
		insertLength,
		changed: deleteLength > 0 || '' !== insertText,
	};
}

