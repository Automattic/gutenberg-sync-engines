/**
 * Twin of `wp_de_rtc_strip_core_block_namespace_from_serialized_comments`.
 *
 * @param content Serialized content.
 * @return Content with `wp:core/` delimiter spelling normalized.
 */
function stripCoreBlockNamespace( content: string ): string {
	return content.replace(
		/<!--\s*(\/?)wp:core\/([^\s>]+)([\s\S]*?)-->/g,
		'<!-- $1wp:$2$3-->'
	);
}

/**
 * Twin of `wp_de_rtc_canonicalize_post_content_core_block_names`.
 *
 * @param content Serialized content.
 * @return Canonical content when only implicit-core spelling differs.
 */
export function canonicalizeCoreBlockNames( content: string ): string {
	if ( -1 === content.toLowerCase().indexOf( 'wp:core/' ) ) {
		return content;
	}

	const { roundtrip } = parseAndReserialize( content );
	if ( roundtrip === content ) {
		return content;
	}
	if ( stripCoreBlockNamespace( content ) === roundtrip ) {
		return roundtrip;
	}
	return content;
}

/**
 * Twin of `wp_de_rtc_canonicalize_serialized_block_boundary_whitespace`.
 *
 * @param content Serialized content.
 * @return Content with block-boundary whitespace normalized.
 */
function canonicalizeBoundaryWhitespace( content: string ): string {
	return content
		.replace( /(<!--\s*wp:[\s\S]*?-->)\s+(?=<)/g, '$1' )
		.replace( /(?<=>)\s+(<!--\s*\/wp:[\s\S]*?-->)/g, '$1' )
		.replace( /(<!--\s*\/wp:[\s\S]*?-->)\s+(?=<!--\s*wp:)/g, '$1' );
}

/**
 * Twin of `wp_de_rtc_canonicalize_post_content_for_hash`.
 *
 * @param content Serialized content.
 * @return Canonicalized content for hash evidence.
 */
export function canonicalizeContentForHash( content: string ): string {
	return canonicalizeBoundaryWhitespace(
		canonicalizeCoreBlockNames( content )
	);
}

/**
 * Twin of `wp_de_rtc_hash_content`.
 *
 * @param content Serialized content.
 * @return SHA-256 content hash.
 */
export function hashDeRtcContent( content: string ): string {
	return sha256Hex( canonicalizeContentForHash( content ) );
}

/**
 * Twin of `wp_de_rtc_get_top_level_serialized_block_records`. Returns
 * null where PHP returns a WP_Error (freeform boundary, or a parse →
 * serialize round trip that changes bytes) — the caller falls back to
 * the whole-document `document.replace_unsupported` evidence.
 *
 * @param content Stripped post content.
 * @return Top-level serialized records, or null when unsafe.
 */
export function getTopLevelBlockRecords( content: string ): string[] | null {
	const canonical = canonicalizeContentForHash( content );
	const { blocks } = parseAndReserialize( canonical );
	const records: string[] = [];
	let roundtrip = '';

	for ( const block of blocks ) {
		const serialized = serializeGrammarBlock( block );
		roundtrip += serialized;

		if ( null === block.blockName ) {
			if ( '' !== serialized.trim() ) {
				return null; // Freeform boundary.
			}
			continue;
		}
		records.push( serialized );
	}

	if ( roundtrip !== canonical ) {
		return null; // Round trip changed bytes.
	}
	return records;
}

/**
 * Twin of `wp_de_rtc_get_serialized_block_record_name`.
 *
 * @param record Serialized block record.
 * @return Block name, or null when parsing is ambiguous.
 */
function getBlockRecordName( record: string ): string | null {
	const canonical = canonicalizeContentForHash( record );
	const { blocks } = parseAndReserialize( canonical );

	if (
		1 !== blocks.length ||
		! blocks[ 0 ].blockName ||
		serializeGrammarBlock( blocks[ 0 ] ) !== canonical
	) {
		return null;
	}
	return blocks[ 0 ].blockName;
}

